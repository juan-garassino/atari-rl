class SonicEnv:
    def __init__(self, max_steps):
        import retro
        gc.collect()
        self.env=retro.make(game=GAME_ID,scenario=SCENARIO,render_mode="rgb_array")
        self.frame_repeat, self.max_steps = FRAME_REPEAT, max_steps
        self.buttons=list(self.env.buttons); self.idx={b:i for i,b in enumerate(self.buttons)}
        self.actions=self._actions(); self.act_n=len(self.actions)
        self.reset_trackers()
    def _actions(self):
        def onehot(btns):
            a=np.zeros(len(self.buttons),np.uint8)
            for b in btns:
                if b in self.idx:a[self.idx[b]]=1
            return a
        return [onehot([]),onehot(['LEFT']),onehot(['RIGHT']),onehot(['B']),
                onehot(['RIGHT','B']),onehot(['LEFT','B']),onehot(['DOWN']),
                onehot(['UP']),onehot(['RIGHT','A']),onehot(['LEFT','A'])]
    def reset_trackers(self):
        self.prev_gray=None; self.prev_info={'x':0,'rings':0,'lives':3}
        self.max_x=0; self.steps=0
    def reset(self):
        frame,info=self.env.reset(); self.reset_trackers()
        self.prev_gray=preprocess_frame(frame); return frame
    def _reward(self,info,frame):
        x=float(info.get('x',self.prev_info['x'])); dx=x-self.prev_info['x']
        progress=np.clip(dx/20.0,-1,2); back=-0.5 if dx<-5 else 0
        ring=0.2*(info.get('rings',0)-self.prev_info['rings'])
        death=-20.0 if info.get('lives',3)<self.prev_info['lives'] else 0
        gray=preprocess_frame(frame); motion=0.3*(np.mean(np.abs(gray-self.prev_gray))-0.05)
        self.prev_gray=gray; self.prev_info={'x':x,'rings':info.get('rings',0),'lives':info.get('lives',3)}
        return float(np.clip(progress+ring+motion+back+death,-25,25))
    def step(self,a):
        act=self.actions[a]; total=0; done=False
        for _ in range(self.frame_repeat):
            frame,_,term,trunc,info=self.env.step(act)
            total+=self._reward(info,frame); done=term or trunc
            self.steps+=1
            if done or self.steps>=self.max_steps: done=True; break
        return frame,total,done,info
    def close(self):
        try:self.env.close()
        except:pass

