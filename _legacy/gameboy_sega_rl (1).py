class Rollout:
    def __init__(self): self.clear()
    def add(self,s,a,r,v,lp,d):
        self.s.append(s);self.a.append(a);self.r.append(r)
        self.v.append(v);self.lp.append(lp);self.d.append(d)
    def clear(self): self.s=[];self.a=[];self.r=[];self.v=[];self.lp=[];self.d=[]

def compute_gae(r,v,d,next_v):
    T=len(r);adv=np.zeros(T,np.float32);gae=0
    for t in reversed(range(T)):
        nv=next_v if t==T-1 else v[t+1]
        delta=r[t]+GAMMA*nv*(1-d[t])-v[t]
        gae=delta+GAMMA*LAMBDA*(1-d[t])*gae
        adv[t]=gae
    return adv,adv+v

