class SonicEnv:
    """Retro env with Sonic-specific reward shaping + frame repeat."""
    def __init__(self, game_id=GAME_ID, scenario=SCENARIO, frame_repeat=FRAME_REPEAT, max_steps=MAX_EP_STEPS):
        import retro
        gc.collect()  # ensure no stale emulator remains
        mk = dict(game=game_id, render_mode="rgb_array")
        if scenario is not None:
            mk["scenario"] = scenario
        self.env = retro.make(**mk)
        self.env.render_mode = "rgb_array"  # Explicitly enforce
        self.buttons = list(getattr(self.env, "buttons", []))
        self.idx = {b:i for i,b in enumerate(self.buttons)}
        self.frame_repeat = frame_repeat
        self.max_steps = max_steps

        def onehot(btns):
            a = np.zeros(len(self.buttons), np.uint8)
            for b in btns:
                if b in self.idx: a[self.idx[b]] = 1
            return a

        self.actions = [
            onehot([]),
            onehot(['LEFT']),
            onehot(['RIGHT']),
            onehot(['UP']),
            onehot(['DOWN']),
            onehot(['B']),
            onehot(['A']),
            onehot(['RIGHT','B']),
            onehot(['LEFT','B']),
            onehot(['DOWN','B']),
            onehot(['UP','B']),
            onehot(['RIGHT','A']),
        ]
        self.act_n = len(self.actions)
        self.reset_trackers()

    def reset_trackers(self):
        self.prev_gray = None
        self.prev_info = {'x':0, 'score':0, 'rings':0, 'lives':3}
        self.max_x = 0.0
        self.steps = 0
        self.last_action = None

    def reset(self, *, seed=None, options=None):
        result = self.env.reset(seed=seed)
        if isinstance(result, tuple):
            frame, info = result
        else:
            frame, info = result, {}
        self.reset_trackers()
        self.prev_gray = preprocess_frame(frame)
        for k in self.prev_info:
            if k in info: self.prev_info[k] = info[k]
        self.max_x = float(self.prev_info.get('x', 0))
        self.last_action = None
        return frame, info

    def _sonic_reward(self, info, frame, action):
        x = float(info.get('x', self.prev_info.get('x', 0)))
        score = float(info.get('score', self.prev_info.get('score', 0)))
        rings = float(info.get('rings', self.prev_info.get('rings', 0)))
        lives = int(info.get('lives', self.prev_info.get('lives', 3)))

        x_delta = x - max(self.max_x, 0)
        progress_reward = 0.12 * max(0.0, x_delta)
        self.max_x = max(self.max_x, x)
        back_penalty = -0.08 * abs(x_delta) if x_delta < 0 else 0.0

        ring_delta = rings - self.prev_info.get('rings', 0)
        score_delta = score - self.prev_info.get('score', 0)
        ring_reward = 0.7 * max(0.0, ring_delta)
        score_reward = 0.001 * max(0.0, score_delta)
        lives_delta = lives - self.prev_info.get('lives', 3)
        death_penalty = -5.0 if lives_delta < 0 else 0.0

        gray = preprocess_frame(frame)
        pixel_change = float(np.mean(np.abs(gray - self.prev_gray)))
        pixel_bonus = 0.05 * pixel_change
        stagnation_penalty = -0.02 if x_delta == 0 and pixel_change < 0.1 else 0.0

        jump_bonus = 0.0
        combined_jump_bonus = 0.0
        is_jump = self.actions[action].tolist().count(1) > 0 and (self.actions[action][self.idx.get('B', -1)] == 1 or self.actions[action][self.idx.get('A', -1)] == 1)
        if is_jump:
            if x_delta > 0: jump_bonus = 0.3
            if sum(self.actions[action]) > 1:
                combined_jump_bonus = 0.4 if (x_delta > 0 or ring_delta > 0) else 0.0

        shaped = progress_reward + back_penalty + ring_reward + score_reward + death_penalty + pixel_bonus + stagnation_penalty + jump_bonus + combined_jump_bonus

        self.prev_gray = gray
        self.prev_info = {'x':x, 'score':score, 'rings':rings, 'lives':lives}
        self.last_action = action
        return shaped

    def step(self, a):
        done = False
        last_frame, last_info = None, {}
        act = self.actions[a]
        for _ in range(self.frame_repeat):
            result = self.env.step(act)
            if len(result) == 5:
                frame, _, term, trunc, info = result
            else:
                frame, _, done_flag, info = result
                term, trunc = done_flag, False
            last_frame, last_info = frame, info
            done = term or trunc
            if done: break

        r = self._sonic_reward(last_info, last_frame, a)
        self.steps += 1
        if self.steps >= self.max_steps: done = True
        return last_frame, r, done, False, last_info

    def render(self):
        return self.env.render()

    def close(self):
        try:
            self.env.close()
        except Exception:
            pass

