class Rollout:
    def __init__(self): self.clear()
    def add(self,s,a,r,v,lp,d):
        self.s.append(s);self.a.append(a);self.r.append(r)
        self.v.append(v);self.lp.append(lp);self.d.append(d)
    def clear(self): self.s=[];self.a=[];self.r=[];self.v=[];self.lp=[];self.d=[]

def compute_gae(r,v,d,next_v):
    T=len(r);adv=np.zeros(T,np.float32);gae=0
    for t in reversed(range(T)):
        nv=next_v if t==T-1 else v[t+1]
        delta=r[t]+GAMMA*nv*(1-d[t])-v[t]
        gae=delta+GAMMA*LAMBDA*(1-d[t])*gae
        adv[t]=gae
    return adv,adv+v

def record(policy, steps, path):
    """Record short gameplay safely (no None frames, no Retro crash)."""
    import imageio, gc
    env = SonicEnv(CFG["MAX_EP_STEPS"])
    fs = FrameStack()
    obs = fs.reset(env.reset())
    writer = imageio.get_writer(path, fps=60, macro_block_size=1)
    total = 0.0
    try:
        for _ in range(steps):
            x = torch.from_numpy(obs).unsqueeze(0).to(DEVICE)
            with torch.no_grad():
                logits, _ = policy(x)
                a = torch.distributions.Categorical(logits=logits).sample().item()
            frame, r, done, _ = env.step(a)
            total += r

            # 🩹 FIX: skip None or invalid frames
            if frame is not None and isinstance(frame, np.ndarray):
                try:
                    frame = cv2.cvtColor(frame, cv2.COLOR_RGB2BGR)
                    writer.append_data(frame)
                except Exception as e:
                    console.print(f"[red]⚠️ Frame skipped: {e}")

            obs = fs.push(frame if frame is not None else np.zeros_like(obs[0]))
            if done:
                obs = fs.reset(env.reset())
        writer.close()
        console.print(f"[blue]🎥 Saved video → {path} | Reward≈{total:.2f}")
    finally:
        env.close()
        gc.collect()


