class SonicEnv:
    def __init__(self, max_steps):
        import retro
        gc.collect()
        self.env = retro.make(game=GAME_ID, scenario=SCENARIO, render_mode="rgb_array")
        self.frame_repeat, self.max_steps = FRAME_REPEAT, max_steps
        self.buttons = list(self.env.buttons)
        self.idx = {b: i for i, b in enumerate(self.buttons)}
        self.actions = self._actions()
        self.act_n = len(self.actions)
        self.reset_trackers()

    def _actions(self):
        def onehot(btns):
            a = np.zeros(len(self.buttons), np.uint8)
            for b in btns:
                if b in self.idx:
                    a[self.idx[b]] = 1
            return a

        return [
            onehot([]),
            onehot(["LEFT"]),
            onehot(["RIGHT"]),
            onehot(["B"]),
            onehot(["RIGHT", "B"]),
            onehot(["LEFT", "B"]),
            onehot(["DOWN"]),
            onehot(["UP"]),
            onehot(["RIGHT", "A"]),
            onehot(["LEFT", "A"]),
        ]

    def reset_trackers(self):
        # Track both position and velocity for momentum reward
        self.prev_gray = None
        self.prev_info = {"x": 0.0, "y": 0.0, "rings": 0, "lives": 3}
        self.max_x = 0.0
        self.prev_dx = 0.0
        self.steps = 0

    def reset(self):
        frame, info = self.env.reset()
        self.reset_trackers()
        # Seed state
        self.prev_info["x"] = float(info.get("x", 0.0))
        self.prev_info["y"] = float(info.get("y", 0.0))
        self.prev_info["rings"] = int(info.get("rings", 0))
        self.prev_info["lives"] = int(info.get("lives", 3))
        self.max_x = self.prev_info["x"]
        self.prev_gray = preprocess_frame(frame)
        return frame

    def _reward(self, info, frame):
        """
        Momentum-aware, spring-friendly reward:
        - Net forward progress only (no punishment for backtracking)
        - Vertical motion bonus (springs, walls)
        - Momentum bonus (maintain speed or smooth acceleration)
        - Curiosity from frame change
        - Rings and death
        - Anti-stagnation penalty
        """
        # Current telemetry
        x = float(info.get("x", self.prev_info["x"]))
        y = float(info.get("y", self.prev_info["y"]))
        rings = int(info.get("rings", self.prev_info["rings"]))
        lives = int(info.get("lives", self.prev_info["lives"]))

        dx = x - self.prev_info["x"]
        dy = y - self.prev_info["y"]
        ring_delta = rings - self.prev_info["rings"]
        life_delta = lives - self.prev_info["lives"]

        # ---- net forward progress ----
        forward_progress = 0.0
        if x > self.max_x:
            forward_progress = 0.15 * (x - self.max_x)
            self.max_x = x

        # ---- vertical movement (springs / jumping) ----
        vertical_reward = 0.10 * np.clip(dy, -5.0, 10.0)

        # ---- momentum bonus ----
        # reward maintaining same direction & speed, penalize abrupt reversals
        momentum = 0.0
        if abs(dx) > 0.1:
            # if moving forward consistently
            if dx * self.prev_dx > 0:
                momentum = 0.05 * (abs(dx) + abs(self.prev_dx))
            # if suddenly reversed direction → penalty
            elif dx * self.prev_dx < 0:
                momentum = -0.1 * abs(dx)
        self.prev_dx = dx

        # ---- curiosity / motion-based exploration ----
        gray = preprocess_frame(frame)
        motion = np.mean(np.abs(gray - self.prev_gray)) if self.prev_gray is not None else 0.0
        motion_reward = 0.40 * (motion - 0.05)

        # ---- rings / death ----
        ring_bonus = 0.60 * np.clip(ring_delta, -5, 10)
        death_penalty = -20.0 if life_delta < 0 else 0.0

        # ---- anti-stagnation ----
        stagnation_penalty = -0.30 if (abs(dx) < 1.0 and abs(dy) < 1.0) else 0.0

        # ---- total reward ----
        total = (
            forward_progress
            + vertical_reward
            + momentum
            + ring_bonus
            + motion_reward
            + death_penalty
            + stagnation_penalty
        )
        total = float(np.clip(total, -25.0, 25.0))

        # update trackers
        self.prev_gray = gray
        self.prev_info = {"x": x, "y": y, "rings": rings, "lives": lives}
        return total

    def step(self, a):
        act = self.actions[a]
        total = 0
        done = False
        for _ in range(self.frame_repeat):
            frame, _, term, trunc, info = self.env.step(act)
            total += self._reward(info, frame)
            done = term or trunc
            self.steps += 1
            if done or self.steps >= self.max_steps:
                done = True
                break
        return frame, total, done, info

    def close(self):
        try:
            self.env.close()
        except:
            pass

