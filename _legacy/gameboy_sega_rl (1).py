def preprocess_frame(frame):
    img = Image.fromarray(frame).resize((IMG_SIZE, IMG_SIZE)).convert("L")
    return np.array(img, dtype=np.float32) / 255.0

class FrameStack:
    def __init__(self, k=FRAME_STACK): self.k, self.frames = k, None
    def reset(self, frame): f = preprocess_frame(frame); self.frames = np.stack([f]*self.k,0); return self.frames
    def push(self, frame): f = preprocess_frame(frame); self.frames = np.concatenate([self.frames[1:], f[None]],0); return self.frames

