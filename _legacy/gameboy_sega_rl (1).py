class ResidualBlock(nn.Module):
    def __init__(self, in_ch, out_ch, stride=1, groups=8):
        super().__init__()
        self.conv1 = nn.Conv2d(in_ch, out_ch, 3, stride, 1)
        self.gn1 = nn.GroupNorm(num_groups=min(groups, out_ch), num_channels=out_ch)
        self.act = nn.SiLU()
        self.conv2 = nn.Conv2d(out_ch, out_ch, 3, 1, 1)
        self.gn2 = nn.GroupNorm(num_groups=min(groups, out_ch), num_channels=out_ch)
        self.skip = nn.Conv2d(in_ch, out_ch, 1, stride) if (in_ch != out_ch or stride != 1) else nn.Identity()
    def forward(self, x):
        identity = self.skip(x)
        out = self.act(self.gn1(self.conv1(x)))
        out = self.gn2(self.conv2(out))
        out += identity
        return self.act(out)

class CNNPolicy(nn.Module):
    def __init__(self, act_n, dropout_p=0.1):
        super().__init__()
        c = FRAME_STACK
        self.stem = nn.Sequential(
            nn.Conv2d(c, 32, 8, 4, 2),
            nn.GroupNorm(4, 32),
            nn.SiLU(),
        )
        self.stage1 = ResidualBlock(32, 64, stride=2)
        self.stage2 = ResidualBlock(64, 64, stride=1)
        self.stage3 = ResidualBlock(64, 128, stride=2)
        self.tail = nn.Sequential(
            nn.Conv2d(128, 128, 3, 1, 1),
            nn.GroupNorm(8, 128),
            nn.SiLU(),
        )
        self.flatten = nn.Flatten()
        self.dropout = nn.Dropout(dropout_p)
        self.fc = nn.Linear(128 * 6 * 6, 512)
        self.ln = nn.LayerNorm(512)
        self.act = nn.SiLU()
        self.pi = nn.Linear(512, act_n)
        self.v = nn.Linear(512, 1)
    def forward(self, x):
        z = self.stem(x)
        z = self.stage1(z)
        z = self.stage2(z)
        z = self.stage3(z)
        z = self.tail(z)
        z = self.flatten(z)
        z = self.act(self.ln(self.fc(self.dropout(z))))
        return self.pi(z), self.v(z).squeeze(-1)

