def preprocess_frame(frame):
    frame = np.array(frame)
    gray = cv2.cvtColor(frame, cv2.COLOR_RGB2GRAY)
    resized = cv2.resize(gray, (IMG_SIZE, IMG_SIZE))
    return resized.astype(np.float32)/255.0

class FrameStack:
    def __init__(self,k=FRAME_STACK): self.k=k; self.frames=None
    def reset(self,frame):
        f=preprocess_frame(frame); self.frames=np.stack([f]*self.k,0); return self.frames
    def push(self,frame):
        f=preprocess_frame(frame); self.frames=np.concatenate([self.frames[1:],f[None]],0); return self.frames

