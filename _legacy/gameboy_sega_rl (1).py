def train():
    env = SonicEnv(CFG["MAX_EP_STEPS"])
    policy = CNNPolicy(env.act_n).to(DEVICE)
    opt = torch.optim.Adam(policy.parameters(), lr=LR)
    fs = FrameStack()
    obs = fs.reset(env.reset())
    buf = Rollout()
    total_steps = 0
    episode_rewards = []
    current_r = 0
    video_milestones = set(int(CFG["TOTAL_STEPS"] * p) for p in np.arange(0.05, 1.05, 0.05))
    checkpoint_milestones = set(int(CFG["TOTAL_STEPS"] * p) for p in np.arange(0.01, 1.05, 0.01))

    with Progress(SpinnerColumn(), *Progress.get_default_columns(),
                  TimeElapsedColumn(), console=console) as progress:
        task = progress.add_task("[cyan]Training", total=CFG["TOTAL_STEPS"])
        for it in range(CFG["TOTAL_STEPS"] // CFG["ROLLOUT_STEPS"]):
            for _ in range(CFG["ROLLOUT_STEPS"]):
                x = torch.from_numpy(obs).unsqueeze(0).to(DEVICE)
                with torch.no_grad():
                    logits, v = policy(x)
                    dist = torch.distributions.Categorical(logits=logits)
                    a = dist.sample()
                    lp = dist.log_prob(a)
                frame, r, done, _ = env.step(int(a.item()))
                buf.add(obs, int(a.item()), r, float(v.item()), float(lp.item()), float(done))
                current_r += r
                obs = fs.push(frame)
                total_steps += 1
                progress.update(task, advance=1)
                if done:
                    episode_rewards.append(current_r)
                    current_r = 0
                    obs = fs.reset(env.reset())
                if total_steps in video_milestones:
                    ckpt = f"{CFG['SAVE_DIR']}/models/sonic_step_{total_steps}.pt"
                    torch.save(policy.state_dict(), ckpt)
                    console.print(f"[green]💾 Saved checkpoint at {total_steps:,}")
                    env.close()
                    gc.collect()
                    record(policy, CFG["VIDEO_STEPS"],
                           f"{CFG['SAVE_DIR']}/videos/sonic_p{int(100*total_steps/CFG['TOTAL_STEPS']):02d}.mp4")
                    env = SonicEnv(CFG["MAX_EP_STEPS"])
                    fs = FrameStack()
                    obs = fs.reset(env.reset())
                elif total_steps in checkpoint_milestones:
                    ckpt = f"{CFG['SAVE_DIR']}/models/sonic_step_{total_steps}.pt"
                    torch.save(policy.state_dict(), ckpt)
                    console.print(f"[green]💾 Quick checkpoint at {total_steps:,}")

            with torch.no_grad():
                _, next_v = policy(torch.from_numpy(obs).unsqueeze(0).to(DEVICE))
            s, a, r, v, lp, d = map(np.asarray, (buf.s, buf.a, buf.r, buf.v, buf.lp, buf.d))
            adv, ret = compute_gae(r, v, d, next_v.item())
            adv = (adv - adv.mean()) / (adv.std() + 1e-8)
            S = torch.tensor(s).float().to(DEVICE)
            A = torch.tensor(a).long().to(DEVICE)
            LP = torch.tensor(lp).float().to(DEVICE)
            ADV = torch.tensor(adv).float().to(DEVICE)
            RET = torch.tensor(ret).float().to(DEVICE)
            for _ in range(CFG["EPOCHS"]):
                idx = np.random.permutation(len(S))
                for st in range(0, len(S), CFG["BATCH_SIZE"]):
                    j = idx[st:st + CFG["BATCH_SIZE"]]
                    logits, values = policy(S[j])
                    dist = torch.distributions.Categorical(logits=logits)
                    logp = dist.log_prob(A[j])
                    entropy = dist.entropy().mean()
                    ratio = torch.exp(logp - LP[j])
                    s1 = ratio * ADV[j]
                    s2 = torch.clamp(ratio, 1 - CLIP_EPS, 1 + CLIP_EPS) * ADV[j]
                    pol_loss = -torch.min(s1, s2).mean()
                    val_loss = 0.5 * (RET[j] - values).pow(2).mean()
                    loss = pol_loss + VF_COEF * val_loss - ENT_COEF * entropy
                    opt.zero_grad()
                    loss.backward()
                    nn.utils.clip_grad_norm_(policy.parameters(), 0.5)
                    opt.step()
            buf.clear()
            if (it + 1) % 5 == 0:
                avg = np.mean(episode_rewards[-10:]) if episode_rewards else 0
                table = Table(title=f"Iter {it+1}", show_header=True, header_style="bold cyan")
                table.add_column("Metric")
                table.add_column("Value", style="yellow")
                table.add_row("Steps", f"{total_steps:,}")
                table.add_row("Avg Reward", f"{avg:.2f}")
                console.print(table)
                console.rule()
    env.close()
    torch.save(policy.state_dict(), f"{CFG['SAVE_DIR']}/models/sonic_final.pt")
    console.print(f"[bold green]✅ Training complete — model saved.")
    return policy

