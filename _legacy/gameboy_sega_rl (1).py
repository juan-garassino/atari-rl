# =========================================
class GenesisEnvLite:
    """Genesis wrapper with combos, frame repeat, and game-aware reward shaping."""
    def __init__(self, game_id, frame_repeat=4, max_steps=10000):
        import retro
        self.env = retro.make(game=game_id, render_mode="rgb_array")
        self.buttons = list(getattr(self.env, "buttons", []))  # e.g., ['B','C','A','START','UP','DOWN','LEFT','RIGHT','Z','Y','X','MODE']
        self.idx = {b:i for i,b in enumerate(self.buttons)}
        self.frame_repeat = frame_repeat
        self.max_steps = max_steps

        # --- define a compact yet expressive action set (good for Airstriker) ---
        def onehot(btns):
            a = np.zeros(len(self.buttons), np.uint8)
            for b in btns:
                if b in self.idx: a[self.idx[b]] = 1
            return a

        self.actions = [
            onehot([]),                 # 0: no-op
            onehot(['LEFT']),           # 1
            onehot(['RIGHT']),          # 2
            onehot(['UP']),             # 3
            onehot(['DOWN']),           # 4
            onehot(['B']),              # 5: shoot (often 'B')
            onehot(['A']),              # 6: alt action
            onehot(['RIGHT','B']),      # 7: move+shoot combos
            onehot(['LEFT','B']),       # 8
            onehot(['UP','B']),         # 9
            onehot(['DOWN','B']),       # 10
            onehot(['RIGHT','A']),      # 11
        ]
        self.act_n = len(self.actions)

        # trackers
        self.prev_gray = None
        self.prev_score = 0.0
        self.prev_x = 0.0
        self.prev_lives = None
        self.steps = 0

    def reset(self):
        f, info = self.env.reset()
        self.prev_gray = preprocess_frame(f)
        self.prev_score = float(info.get('score', 0) or 0)
        self.prev_x = float(info.get('x', 0) or 0)
        self.prev_lives = info.get('lives', None)
        self.steps = 0
        return f

    def step(self, a):
        total_reward = 0.0
        last_frame = None
        info_out = {}
        done = False

        # repeat selected action for K frames (sticky)
        act = self.actions[a]
        for _ in range(self.frame_repeat):
            f, _, term, trunc, info = self.env.step(act)
            last_frame = f
            info_out = info
            done = term or trunc
            if done: break

        # --- reward shaping ---
        gray = preprocess_frame(last_frame)
        pixel_change = float(np.mean(np.abs(gray - self.prev_gray)))  # exploration fallback
        score = float(info_out.get('score', self.prev_score))
        x_pos = float(info_out.get('x', self.prev_x))
        lives = info_out.get('lives', self.prev_lives)

        score_delta = (score - self.prev_score)
        x_delta = (x_pos - self.prev_x)
        lives_delta = 0.0
        if (self.prev_lives is not None) and (lives is not None):
            lives_delta = float(lives - self.prev_lives)  # negative when losing a life

        # weights tuned for shmup-style games like Airstriker
        shaped = (
            0.20 * pixel_change +
            0.02 * (score_delta) +        # reward scoring
            0.005 * (x_delta) +           # slight reward for forward progress if exposed
            (-0.5 if lives_delta < 0 else 0.0)  # penalize life loss
        )
        total_reward = shaped

        # update trackers
        self.prev_gray = gray
        self.prev_score = score
        self.prev_x = x_pos
        self.prev_lives = lives
        self.steps += 1

        truncated = (self.steps >= self.max_steps)
        return last_frame, total_reward, (done or truncated), info_out

    def close(self):
        self.env.close()


# =========================================
# 3. Tiny PPO-like CNN Policy
# =========================================
class CNNPolicy(nn.Module):
    def __init__(self, act_n):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(FRAME_STACK,32,8,4), nn.ReLU(),
            nn.Conv2d(32,64,4,2), nn.ReLU(),
            nn.Conv2d(64,64,3,1), nn.ReLU()
        )
        self.fc = nn.Sequential(nn.Linear(64*7*7,512), nn.ReLU())
        self.pi, self.v = nn.Linear(512,act_n), nn.Linear(512,1)
    def forward(self,x):
        z=self.conv(x).view(x.size(0),-1)
        z=self.fc(z)
        return self.pi(z), self.v(z).squeeze(-1)

# =========================================
# 4. Minimal training loop
# =========================================
def train(env, act_n, tag):
    policy = CNNPolicy(act_n).to(DEVICE)
    opt = torch.optim.Adam(policy.parameters(), lr=2.5e-4)
    fs, obs, done = FrameStack(), env.reset(), False
    obs = fs.reset(obs)

    # rolling normalization for reward
    r_hist = []

    for step in trange(TOTAL_STEPS, desc=f"Training {tag}"):
        x = torch.from_numpy(obs).unsqueeze(0).to(DEVICE)

        # temperature schedule for early exploration
        temperature = max(0.7, 1.5 - 1.0 * (step / TOTAL_STEPS))  # 1.5 -> 0.7
        logits, v = policy(x)
        dist = torch.distributions.Categorical(logits=logits / temperature)
        a = dist.sample()
        logp = dist.log_prob(a)

        # ε-greedy mix on top of entropy/temperature
        eps = max(0.05, 0.25 - 0.20 * (step / TOTAL_STEPS))  # 0.25 -> 0.05
        if np.random.rand() < eps:
            a = torch.tensor(np.random.randint(act_n), device=DEVICE)

        f, r, done, _ = env.step(a.item())
        obs = fs.push(f)

        # reward normalization (uses last 200 rewards)
        r_hist.append(r)
        if len(r_hist) > 200:
            r_hist = r_hist[-200:]
        r_n = r
        if len(r_hist) >= 20:
            mu, sd = float(np.mean(r_hist)), float(np.std(r_hist) + 1e-8)
            r_n = (r - mu) / sd

        # add entropy bonus to encourage exploration
        entropy_bonus = 0.02 * dist.entropy().mean()
        loss = (-logp * r_n + 0.5 * v.pow(2).mean() - entropy_bonus)

        opt.zero_grad()
        loss.backward()
        nn.utils.clip_grad_norm_(policy.parameters(), 0.5)
        opt.step()

        if done:
            obs = fs.reset(env.reset())

    os.makedirs("/content/results/models", exist_ok=True)
    torch.save(policy.state_dict(), f"/content/results/models/{tag}.pt")
    print(f"💾 Model saved to /content/results/models/{tag}.pt")
    return policy


