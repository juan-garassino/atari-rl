def train():
    console.rule("[bold green]🚀 Initializing Training")
    vec_env = AsyncVectorEnv([make_env() for _ in range(NUM_ENVS)])
    policy = CNNPolicy(vec_env.action_space[0].n).to(DEVICE)
    opt = torch.optim.Adam(policy.parameters(), lr=LR, eps=1e-5)
    fs = [FrameStack() for _ in range(NUM_ENVS)]
    obs, infos = vec_env.reset()
    obs = np.stack([fs[i].reset(o) for i, o in enumerate(obs)])
    total_frames = 0

    def get_state_vec(info):
        x = float(info.get('x', 0)) / 4096.0
        rings = float(info.get('rings', 0)) / 100.0
        lives = float(info.get('lives', 3)) / 5.0
        score = float(info.get('score', 0)) / 10000.0
        return np.array([x, rings, lives, score], dtype=np.float32)

    buf = Rollout()
    episode_rewards, episode_lengths = [[] for _ in range(NUM_ENVS)], [[] for _ in range(NUM_ENVS)]
    current_ep_rewards = [0.0] * NUM_ENVS
    current_ep_lengths = [0] * NUM_ENVS

    with Progress(SpinnerColumn(), *Progress.get_default_columns(), TimeElapsedColumn(), console=console) as progress:
        task = progress.add_task("[cyan]Training Progress", total=TOTAL_STEPS)
        for iteration in range(TOTAL_STEPS // ROLLOUT_STEPS):
            iter_start = time.time()
            for _ in range(ROLLOUT_STEPS):
                x = torch.from_numpy(obs).float().to(DEVICE)
                state_vecs_np = np.stack([get_state_vec(infos[i]) for i in range(NUM_ENVS)])
                state_vecs = torch.from_numpy(state_vecs_np).float().to(DEVICE)
                with torch.no_grad():
                    logits, v = policy(x, state_vecs)
                    dist = torch.distributions.Categorical(logits=logits)
                    a = dist.sample()
                    lp = dist.log_prob(a)
                next_obs, r, done, trunc, infos = vec_env.step(a.cpu().numpy())
                for i in range(NUM_ENVS):
                    buf.add(obs[i], state_vecs_np[i], a[i].item(), float(r[i]), float(v[i].item()), float(lp[i].item()), float(done[i] or trunc[i]))
                    current_ep_rewards[i] += r[i]
                    current_ep_lengths[i] += 1
                    if done[i] or trunc[i] or current_ep_lengths[i] >= MAX_EP_STEPS:
                        episode_rewards[i].append(current_ep_rewards[i])
                        episode_lengths[i].append(current_ep_lengths[i])
                        current_ep_rewards[i] = 0.0
                        current_ep_lengths[i] = 0
                        next_obs_i, info_i = vec_env.reset(index=i)
                        next_obs[i] = next_obs_i
                        infos[i] = info_i
                        obs[i] = fs[i].reset(next_obs[i])
                    else:
                        obs[i] = fs[i].push(next_obs[i])
                total_frames += NUM_ENVS
                progress.update(task, advance=NUM_ENVS)

            with torch.no_grad():
                state_vecs_np = np.stack([get_state_vec(infos[i]) for i in range(NUM_ENVS)])
                state_vecs = torch.from_numpy(state_vecs_np).float().to(DEVICE)
                _, next_v = policy(torch.from_numpy(obs).float().to(DEVICE), state_vecs)
                next_v = next_v.mean().item()
            s = np.asarray(buf.s, dtype=np.float32)
            state_vecs_buf = np.asarray(buf.state_vec, dtype=np.float32)
            a = np.asarray(buf.a, dtype=np.int64)
            r = np.asarray(buf.r, dtype=np.float32)
            v = np.asarray(buf.v, dtype=np.float32)
            lp = np.asarray(buf.lp, dtype=np.float32)
            d = np.asarray(buf.d, dtype=np.float32)
            adv, ret = compute_gae(r, v, d, next_v)
            adv = (adv - adv.mean()) / (adv.std() + 1e-8)

            S = torch.from_numpy(s).to(DEVICE)
            STATE_VECS = torch.from_numpy(state_vecs_buf).to(DEVICE)
            A = torch.from_numpy(a).to(DEVICE)
            LP = torch.from_numpy(lp).to(DEVICE)
            ADV = torch.from_numpy(adv).to(DEVICE)
            RET = torch.from_numpy(ret).to(DEVICE)
            N = len(S)
            total_loss = 0
            num_updates = 0
            for epoch in range(EPOCHS):
                idx = np.random.permutation(N)
                for start in range(0, N, BATCH_SIZE):
                    j = idx[start:start+BATCH_SIZE]
                    logits, values = policy(S[j], STATE_VECS[j])
                    dist = torch.distributions.Categorical(logits=logits)
                    logp = dist.log_prob(A[j])
                    entropy = dist.entropy().mean()
                    ratio = torch.exp(logp - LP[j])
                    surr1 = ratio * ADV[j]
                    surr2 = torch.clamp(ratio, 1.0-CLIP_EPS, 1.0+CLIP_EPS) * ADV[j]
                    pol_loss = -torch.min(surr1, surr2).mean()
                    val_loss = 0.5 * (RET[j] - values).pow(2).mean()
                    loss = pol_loss + VF_COEF*val_loss - ENT_COEF*entropy
                    opt.zero_grad()
                    loss.backward()
                    nn.utils.clip_grad_norm_(policy.parameters(), 0.5)
                    opt.step()
                    total_loss += loss.item()
                    num_updates += 1
            buf.clear()

            if iteration % 20 == 0 or iteration == (TOTAL_STEPS // ROLLOUT_STEPS) - 1:
                table = Table(title=f"Iteration {iteration + 1}", show_header=True, header_style="bold cyan")
                table.add_column("Metric", style="cyan")
                table.add_column("Value", style="yellow")
                table.add_row("Steps Completed", f"{total_frames:,}")
                avg_reward = np.mean([np.mean(rewards[-10:]) if rewards else 0 for rewards in episode_rewards])
                avg_length = np.mean([np.mean(lengths[-10:]) if lengths else 0 for lengths in episode_lengths])
                table.add_row("Avg Episode Reward", f"{avg_reward:.2f}")
                table.add_row("Avg Episode Length", f"{avg_length:.1f}")
                table.add_row("Episodes Completed", f"{sum(len(rewards) for rewards in episode_rewards)}")
                table.add_row("Avg Loss", f"{total_loss / max(num_updates, 1):.4f}")
                console.print(table)
                console.rule()

            if total_frames % 100_000 < NUM_ENVS:
                torch.save(policy.state_dict(), f"{SAVE_DIR}/models/ckpt_{total_frames}.pt")
                console.print(f"[green]💾 Checkpoint saved → {SAVE_DIR}/models/ckpt_{total_frames}.pt")

    vec_env.close()
    torch.save(policy.state_dict(), MODEL_PATH)
    console.print(f"[bold green]💾 Saved model → {MODEL_PATH}")
    return policy

