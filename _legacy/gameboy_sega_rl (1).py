# Compatibility wrapper for old gym environments
class EnvCompatibility(gym.Wrapper):
    """Converts old gym (step returns 4 values) to new gymnasium (step returns 5 values)."""
    def __init__(self, env):
        super().__init__(env)

    def reset(self, **kwargs):
        # Handle both old and new reset signatures
        result = self.env.reset(**kwargs)
        if isinstance(result, tuple):
            return result  # Already returns (obs, info)
        return result, {}  # Old gym returns just obs

    def step(self, action):
        result = self.env.step(action)
        if len(result) == 4:
            # Old gym: (obs, reward, done, info) -> new: (obs, reward, terminated, truncated, info)
            obs, reward, done, info = result
            return obs, reward, done, False, info
        return result  # Already 5 values

