class Rollout:
    def __init__(self):
        self.s, self.state_vec, self.a, self.r, self.v, self.lp, self.d = [], [], [], [], [], [], []
    def add(self, s, state_vec, a, r, v, lp, d):
        self.s.append(s); self.state_vec.append(state_vec); self.a.append(a); self.r.append(r); self.v.append(v); self.lp.append(lp); self.d.append(d)
    def clear(self): self.__init__()

def compute_gae(rew, val, done, next_v):
    T = len(rew)
    adv = np.zeros(T, dtype=np.float32)
    gae = 0.0
    for t in reversed(range(T)):
        nv = next_v if t == T-1 else val[t+1]
        delta = rew[t] + GAMMA * nv * (1.0 - done[t]) - val[t]
        gae = delta + GAMMA * GAE_LAMBDA * (1.0 - done[t]) * gae
        adv[t] = gae
    ret = adv + val
    return adv, ret

