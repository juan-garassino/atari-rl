class CNNPolicy(nn.Module):
    def __init__(self, act_n):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(FRAME_STACK, 32, 8, 4), nn.ReLU(),
            nn.Conv2d(32, 64, 4, 2), nn.ReLU(),
            nn.Conv2d(64, 64, 3, 1), nn.ReLU()
        )
        cnn_out_dim = 64 * 7 * 7
        state_dim = 4
        self.fc = nn.Sequential(nn.Linear(cnn_out_dim + state_dim, 512), nn.ReLU())
        self.pi = nn.Linear(512, act_n)
        self.v = nn.Linear(512, 1)

    def forward(self, x, state_vec):
        z = self.conv(x).view(x.size(0), -1)
        z = torch.cat([z, state_vec], dim=1)
        z = self.fc(z)
        return self.pi(z), self.v(z).squeeze(-1)

