def record(env, policy, path, fps=30, steps=1000):
    fs, obs = FrameStack(), env.reset()
    obs = fs.reset(obs)
    writer = imageio.get_writer(path, fps=fps, macro_block_size=1)
    for _ in trange(steps, desc="Recording"):
        x = torch.from_numpy(obs).unsqueeze(0).to(DEVICE)
        with torch.no_grad():
            logits, _ = policy(x)
            a = torch.distributions.Categorical(logits=logits).sample().item()
        f, _, done, _ = env.step(a)
        writer.append_data(f)
        obs = fs.push(f)
        if done: break
    writer.close(); print("🎥 Saved:", path)

